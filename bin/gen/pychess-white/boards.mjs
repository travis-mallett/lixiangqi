import { JSDOM } from 'jsdom';
import { readFileSync, writeFileSync } from 'node:fs';

import {
  faceRadius,
  fmt,
  geometryMetadata,
  gridSegments,
  height,
  hexagon,
  labelUses,
  line,
  palaceSegments,
  polygon,
  width,
} from '../three-player-xiangqi/geometry.mjs';

export function generateBoards(read) {
  const source = read('xiangqiLightWood.png');
  const original = new JSDOM(read('xiangqiWikimedia.svg'), { contentType: 'image/svg+xml' });
  const river = original.window.document.querySelector('svg > g > g > g').outerHTML;
  // PyChess publishes this board only as a raster. Keep its original bytes;
  // use the unmarked top margin as a grain strip in an SVG pattern.
  // Its 42px crop excludes the first grid line at y=46.9. The long stretch
  // retains the source's fine vertical grain without repeating horizontal seams.
  const material = `<image id="source-wood" width="844" height="938" href="data:image/png;base64,${source.toString('base64')}"/>
    <pattern id="light-wood" width="1" height="1" viewBox="0 0 844 42" preserveAspectRatio="none">
      <svg width="844" height="42" viewBox="0 0 844 42" overflow="hidden"><use href="#source-wood"/></svg>
    </pattern>`;
  const save = (suffix, w, h, content, defs = '', viewBox = `0 0 ${w} ${h}`) =>
    writeFileSync(
      new URL(`../../../public/images/board/svg/xiangqi-light-wood${suffix}.svg`, import.meta.url),
      `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${viewBox}">
  <title>PyChess Light Wood${suffix}</title>
  <desc>Adapted from PyChess original artwork; canonical LiXiangQi grid. Generated by bin/gen/pychess-white/generate.mjs. Source provenance in bin/gen/pychess-white/source.json.</desc>
  <defs>${material}${defs}</defs>
  ${content}
</svg>\n`,
    );
  const ink = (id, d) => `<path id="${id}" d="${d}" fill="none" stroke="#000000" stroke-width="1.96"/>`;
  // Canonical 900x1000 artwork: 98-unit pitch; intersections (58,59)..(842,941).
  const rows = Array.from({ length: 10 }, (_, i) => `M58,${59 + 98 * i}H842`).join('');
  const files = Array.from({ length: 9 }, (_, i) => `M${58 + 98 * i},59V451M${58 + 98 * i},549V941`).join('');
  const sides = 'M58,451V549M842,451V549';
  const palaces = 'M352,59L548,255M548,59L352,255M352,745L548,941M548,745L352,941';
  const mark = (x, y, left = true, right = true) =>
    [
      ...(left ? [`M${x - 6},${y - 25}V${y - 6}H${x - 25}`, `M${x - 6},${y + 25}V${y + 6}H${x - 25}`] : []),
      ...(right ? [`M${x + 6},${y - 25}V${y - 6}H${x + 25}`, `M${x + 6},${y + 25}V${y + 6}H${x + 25}`] : []),
    ].join('');
  const marks = [2, 7]
    .flatMap(r => [1, 7].map(f => mark(58 + f * 98, 59 + r * 98)))
    .concat([3, 6].flatMap(r => [0, 2, 4, 6, 8].map(f => mark(58 + f * 98, 59 + r * 98, f > 0, f < 8))))
    .join('');
  save(
    '',
    900,
    1000,
    `<rect width="900" height="1000" fill="url(#light-wood)"/>
    ${ink('gridlines', rows + files + sides)}${ink('palaces', palaces)}${ink('position-marks', marks)}
    <g id="river-labels" transform="translate(9 10) scale(.98)">${river}</g>`,
  );
  const mini = Array.from({ length: 7 }, (_, i) => `M${56 + 98 * i},56V644M56,${56 + 98 * i}H644`).join('');
  save(
    '-minixiangqi',
    700,
    700,
    `<rect width="700" height="700" fill="url(#light-wood)"/>
    ${ink('gridlines', mini)}${ink('palaces', 'M252,56L448,252M448,56L252,252M252,448L448,644M448,448L252,644')}`,
  );
  // Banqi pieces occupy cell centers, not Xiangqi intersections.
  const banqiGrid =
    Array.from({ length: 5 }, (_, i) => `M${48 + 100 * i},48V848`).join('') +
    Array.from({ length: 9 }, (_, i) => `M48,${48 + 100 * i}H448`).join('');
  save(
    '-banqi',
    496,
    896,
    `<rect width="496" height="896" fill="url(#light-wood)"/>${ink('banqi-grid', banqiGrid)}`,
  );
  const glyphs = new JSDOM(
    readFileSync(new URL('../three-player-xiangqi/wudang-glyphs.svg', import.meta.url), 'utf8'),
    { contentType: 'image/svg+xml' },
  );
  const face = polygon(hexagon(faceRadius));
  save(
    '-three-player',
    fmt(width),
    fmt(height),
    `
    <metadata id="three-player-geometry">${JSON.stringify(geometryMetadata)}</metadata>
    <path d="${face}" fill="url(#light-wood)"/>
    ${ink('three-player-grid', gridSegments.map(line).join(''))}
    ${ink('three-player-palaces', palaceSegments.map(line).join(''))}
    <g id="three-player-labels" fill="#000000" color="#000000" aria-label="魏、吳、蜀；荊州、赤壁、祁山">${labelUses().join('')}</g>`,
    glyphs.window.document.querySelector('defs').innerHTML,
    `${fmt(-faceRadius)} ${fmt(-height / 2)} ${fmt(width)} ${fmt(height)}`,
  );
  original.window.close();
  glyphs.window.close();
}
