import { JSDOM } from 'jsdom';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { boardTheme } from './board-theme.mjs';
import {
  radius,
  faceRadius,
  width,
  height,
  sectors,
  hexagon,
  gridSegments,
  palaceSegments,
  fmt,
  line,
  polygon,
  roundedHexagon,
  marker,
  validateGeometry,
  geometryMetadata,
  labelUses,
} from './three-player-xiangqi/geometry.mjs';
export {
  pitch,
  radius,
  apothem,
  margin,
  faceRadius,
  width,
  height,
  sectors,
  pieceCanvas,
  pieceBody,
  rotate,
  point,
  hexagon,
  positions,
  gridSegments,
  palaceDiagonalEdges,
  palaceSegments,
  validateGeometry,
} from './three-player-xiangqi/geometry.mjs';
import { generateThemes } from './three-player-xiangqi/themes.mjs';

export function generate() {
  const boardFile = new URL('../../public/images/board/svg/lixiangqi-default.svg', import.meta.url);
  const source = new JSDOM(readFileSync(boardFile, 'utf8'), { contentType: 'image/svg+xml' });
  const doc = source.window.document;
  const style = boardTheme(doc, 'lixiangqi-default', 98);
  const wood = doc.querySelector('image').getAttribute('href');
  assert.ok(wood.startsWith('data:image/png;base64,'));

  // Copy the canonical engraving, including its measured colors and opacities.
  // Its source board applies scale(0.98) to both artwork and filter distances.
  const engraving = doc.getElementById('xiangqi-river-engraving').cloneNode(true);
  engraving.id = 'three-player-engraving';
  for (const [name, value] of Object.entries({ x: -faceRadius, y: -height / 2, width, height }))
    engraving.setAttribute(name, fmt(value));
  for (const el of engraving.querySelectorAll('*')) {
    el.removeAttribute('id');
    for (const name of ['stdDeviation', 'dx', 'dy'])
      if (el.hasAttribute(name)) el.setAttribute(name, fmt(Number(el.getAttribute(name)) * 0.98));
  }
  const glyphDoc = new JSDOM(
    readFileSync(new URL('./three-player-xiangqi-glyphs.svg', import.meta.url), 'utf8'),
    {
      contentType: 'image/svg+xml',
    },
  );
  const glyphs = glyphDoc.window.document.querySelector('defs').innerHTML;
  const marks = sectors.flatMap((_, s) => [
    ...[1, 7].map(f => marker(f, 2, s)),
    ...[0, 2, 4, 6, 8].map(f => marker(f, 3, s)),
  ]);
  const labels = labelUses();
  const metadata = geometryMetadata;
  // One uniformly scaled crop of the original texture. Its rectangular bevel
  // stays outside the hexagon; the new perimeter supplies a matching wood rim.
  const textureWidth = width + 200;
  const textureHeight = (textureWidth * 1000) / 900;
  const face = roundedHexagon(faceRadius);
  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${fmt(width)}" height="${fmt(height)}" viewBox="${fmt(-faceRadius)} ${fmt(-height / 2)} ${fmt(width)} ${fmt(height)}">
  <title>LiXiangQi default wood — three-player Xiangqi</title>
  <desc>Three rotationally identical nine-file, five-rank territories; 135 piece locations; three rivers and a central triangle. Exact construction in lixiangqi-default-three-player.design.md. Generated by bin/gen/three-player-xiangqi.mjs. Label outlines: FandolKai Regular, GPL with font exception, https://ctan.org/tex-archive/fonts/fandol.</desc>
  <metadata id="three-player-geometry">${JSON.stringify(metadata)}</metadata>
  <defs>
    <clipPath id="three-player-face"><path d="${face}"/></clipPath>
    <linearGradient id="three-player-bevel" x1="0" y1="0" x2="1" y2="1">
      <stop stop-color="#fff6e0" stop-opacity="0.6"/>
      <stop offset="0.48" stop-color="#b38654" stop-opacity="0.2"/>
      <stop offset="1" stop-color="#65422d" stop-opacity="0.6"/>
    </linearGradient>
    ${engraving.outerHTML}
    ${glyphs}
  </defs>
  <g id="three-player-material" clip-path="url(#three-player-face)">
    <image id="three-player-wood" x="${fmt(-textureWidth / 2)}" y="${fmt(-textureHeight / 2)}" width="${fmt(textureWidth)}" height="${fmt(textureHeight)}" preserveAspectRatio="none" href="${wood}"/>
    <path d="${face}" fill="none" stroke="#5b2712" stroke-opacity="0.2" stroke-width="14"/>
    <path d="${roundedHexagon(faceRadius - 3.5)}" fill="none" stroke="url(#three-player-bevel)" stroke-width="5"/>
    <path d="${face}" fill="none" stroke="#65422d" stroke-opacity="0.5" stroke-width="1.5"/>
  </g>
  <g id="three-player-ink" fill="none" stroke="${style.ink}" opacity="${style.opacity}" stroke-linejoin="miter" stroke-linecap="butt">
    <path id="three-player-playing-frame" d="${polygon(hexagon(radius + (2 * style.frame.offset) / Math.sqrt(3)))}" stroke-width="${style.frame.width}"/>
    <path id="three-player-grid" d="${gridSegments.map(line).join('')}" stroke-width="${style.width}"/>
    <path id="three-player-palaces" d="${palaceSegments.map(line).join('')}" stroke-width="${style.width}"/>
    <path id="three-player-position-marks" d="${marks.join('')}" stroke-width="${style.width}"/>
  </g>
  <g id="three-player-labels" fill="#9e8168" filter="url(#three-player-engraving)" aria-label="魏、吴、蜀；荆州、赤壁、祁山">
    ${labels.join('\n    ')}
  </g>
</svg>
`;
  const output = new URL('../../public/images/board/svg/lixiangqi-default-three-player.svg', import.meta.url);
  writeFileSync(output, svg);
  source.window.close();
  glyphDoc.window.close();
  console.log(
    JSON.stringify({ output: fileURLToPath(output), ...validateGeometry(), width, height }, null, 2),
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  generate();
  generateThemes();
}
