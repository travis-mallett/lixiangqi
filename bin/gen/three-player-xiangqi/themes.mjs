import { JSDOM } from 'jsdom';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import {
  faceRadius,
  fmt,
  geometryMetadata,
  gridSegments,
  height,
  hexagon,
  labelUses,
  line,
  marker,
  palaceSegments,
  polygon,
  radius,
  sectors,
  validateGeometry,
  width,
} from './geometry.mjs';
import { paperMaterial, tournamentMaterial, wudangMaterial } from './materials.mjs';

const themes = [
  {
    id: 'tournament',
    source: 'xiangqi-tournament',
    title: 'Tournament',
    material: tournamentMaterial,
    line: 'line',
    mark: 'mark',
    frame: null,
    text: 'g90',
    opacity: 'g91',
  },
  {
    id: 'wudang',
    source: 'xiangqi-wudang',
    title: 'Wudang',
    material: wudangMaterial,
    line: 'xiangqi-coordinate-grid-line',
    mark: 'xiangqi-coordinate-mark',
    frame: 'rect1',
    text: 'g63',
    opacity: 'board-artwork',
  },
  {
    id: 'paper',
    source: 'paper-board',
    title: 'Paper',
    material: paperMaterial,
    line: 'xiangqi-coordinate-grid-line',
    mark: 'xiangqi-coordinate-mark',
    frame: 'rect2',
    text: 'g4',
  },
];

const opacity = element => element?.getAttribute('opacity') || element?.style.opacity || '1';
const attr = (element, name) => {
  for (let el = element; el; el = el.parentElement) if (el.hasAttribute(name)) return el.getAttribute(name);
  throw new Error(`Missing theme attribute: ${name}`);
};

export function generateThemes() {
  validateGeometry();
  for (const theme of themes) {
    const source = new JSDOM(
      readFileSync(new URL(`../../../public/images/board/svg/${theme.source}.svg`, import.meta.url), 'utf8'),
      { contentType: 'image/svg+xml' },
    );
    const glyphs = new JSDOM(readFileSync(new URL(`./${theme.id}-glyphs.svg`, import.meta.url), 'utf8'), {
      contentType: 'image/svg+xml',
    });
    const doc = source.window.document;
    assert.equal(doc.getElementById('board-artwork').getAttribute('transform'), 'scale(0.98)');
    const grid = doc.getElementById(theme.line),
      mark = doc.getElementById(theme.mark),
      text = doc.getElementById(theme.text);
    // Read exact source marker dimensions: tournament uses M15,5H5V15;
    // paper/Wudang use M18,6H6V18. All lengths inherit the source 0.98 scale.
    const markerNumbers = mark.getAttribute('d').match(/^M([\d.]+),([\d.]+)H\2V\1$/);
    assert.ok(markerNumbers, 'Unexpected source marker geometry');
    const marks = sectors.flatMap((_, s) => [
      ...[1, 7].map(f => marker(f, 2, s, Number(markerNumbers[2]) * 0.98, Number(markerNumbers[1]) * 0.98)),
      ...[0, 2, 4, 6, 8].map(f =>
        marker(f, 3, s, Number(markerNumbers[2]) * 0.98, Number(markerNumbers[1]) * 0.98),
      ),
    ]);
    let frame = '';
    if (theme.frame) {
      const rect = doc.getElementById(theme.frame);
      const offset = (-Number(rect.getAttribute('x')) - 400) * 0.98;
      frame = `<path id="three-player-playing-frame" d="${polygon(hexagon(radius + (2 * offset) / Math.sqrt(3)))}" stroke="${attr(rect, 'stroke')}" stroke-width="${fmt(Number(attr(rect, 'stroke-width')) * 0.98)}"/>`;
    }
    const material = theme.material(doc);
    const face = polygon(hexagon(faceRadius));
    const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${fmt(width)}" height="${fmt(height)}" viewBox="${fmt(-faceRadius)} ${fmt(-height / 2)} ${fmt(width)} ${fmt(height)}">
  <title>LiXiangQi ${theme.title} — three-player Xiangqi</title>
  <desc>Exact shared 135-location three-player geometry, with four corner-to-center advisor edges per palace. Source theme: ${theme.source}.svg. Typography and material provenance: three-player-themes.design.md. Geometry contract: lixiangqi-default-three-player.design.md. Generated by bin/gen/three-player-xiangqi.mjs. ${glyphs.window.document.querySelector('desc').textContent}</desc>
  <metadata id="three-player-geometry">${JSON.stringify(geometryMetadata)}</metadata>
  <defs>
    <clipPath id="three-player-face"><path d="${face}"/></clipPath>
    ${material.defs}
    ${glyphs.window.document.querySelector('defs').innerHTML}
  </defs>
  <g id="three-player-material" clip-path="url(#three-player-face)">
    ${material.content}
  </g>
  <g id="three-player-artwork" opacity="${opacity(doc.getElementById(theme.opacity))}">
    <g id="three-player-ink" fill="none" stroke="${attr(grid, 'stroke')}" stroke-linejoin="miter" stroke-linecap="butt">
      ${frame}
      <path id="three-player-grid" d="${gridSegments.map(line).join('')}" stroke-width="${fmt(Number(attr(grid, 'stroke-width')) * 0.98)}"/>
      <path id="three-player-palaces" d="${palaceSegments.map(line).join('')}" stroke-width="${fmt(Number(attr(doc.getElementById(theme.id === 'tournament' ? 'diagonal' : 'xiangqi-coordinate-diagonal'), 'stroke-width')) * 0.98)}"/>
      <path id="three-player-position-marks" d="${marks.join('')}" stroke="${attr(mark, 'stroke')}" stroke-width="${fmt(Number(attr(mark, 'stroke-width')) * 0.98)}"/>
    </g>
    <g id="three-player-labels" fill="${attr(text, 'fill')}" color="${attr(text, 'fill')}" opacity="${opacity(text)}" aria-label="魏、吳、蜀；荊州、赤壁、祁山">
      ${labelUses().join('\n      ')}
    </g>
  </g>
</svg>
`;
    const output = new URL(
      `../../../public/images/board/svg/${theme.source}-three-player.svg`,
      import.meta.url,
    );
    writeFileSync(output, svg);
    console.log(
      JSON.stringify({ output: fileURLToPath(output), theme: theme.id, bytes: Buffer.byteLength(svg) }),
    );
    source.window.close();
    glyphs.window.close();
  }
}
