import { JSDOM } from 'jsdom';
import { readFileSync, writeFileSync } from 'node:fs';

import { boardTheme, boardThemes } from './board-theme.mjs';

// Keep this frame aligned with miniXiangqi.geometry in ui/board/src/definitions.ts.
const size = 700;
const margin = 56;
const step = 98;
for (const theme of Object.keys(boardThemes)) {
  const file = new URL(`../../public/images/board/svg/${theme}.svg`, import.meta.url);
  const dom = new JSDOM(readFileSync(file, 'utf8'), { contentType: 'image/svg+xml' });
  const root = dom.window.document.documentElement;
  const { ink, opacity, width, frame } = boardTheme(dom.window.document, theme, step);
  const background = [...root.children].filter(
    el => ['image', 'rect', 'g'].includes(el.localName) && el.id !== 'board-artwork',
  );
  const needed = new Set();
  const discover = element => {
    for (const match of element.outerHTML.matchAll(/(?:url\(#|href="#)([^)"\s]+)/g)) {
      if (needed.has(match[1])) continue;
      needed.add(match[1]);
      const referenced = root.querySelector(`[id="${match[1]}"]`);
      if (!referenced) throw new Error(`Missing background definition: ${match[1]}`);
      discover(referenced);
    }
  };
  background.forEach(discover);
  const definitions = [...needed].map(id => root.querySelector(`[id="${id}"]`).outerHTML).join('\n');
  const end = size - margin;
  const lines = Array.from({ length: 7 }, (_, i) => {
    const coordinate = margin + i * step;
    return `M${coordinate},${margin}V${end}M${margin},${coordinate}H${end}`;
  }).join('');
  const palace = [margin, margin + 4 * step]
    .map(y => {
      const left = margin + 2 * step;
      const right = margin + 4 * step;
      return `M${left},${y}L${right},${y + 2 * step}M${right},${y}L${left},${y + 2 * step}`;
    })
    .join('');
  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="700" height="700" viewBox="0 0 700 700">
  <title>Mini Xiangqi — ${theme}</title>
  <desc>Seven files and seven ranks, continuous grid, no river. Palaces occupy c1–e3 and c5–e7. Generated by bin/gen/mini-xiangqi-boards.mjs.</desc>
  <defs>${definitions}</defs>
  <g transform="translate(350 350) scale(${size / 900} ${size / 1000})">${background.map(el => el.outerHTML).join('\n')}</g>
  <g id="mini-xiangqi-grid" fill="none" stroke="${ink}" opacity="${opacity}">
    ${frame ? `<rect id="playing-frame" x="${margin - frame.offset}" y="${margin - frame.offset}" width="${end - margin + 2 * frame.offset}" height="${end - margin + 2 * frame.offset}" stroke="${frame.ink}" stroke-width="${frame.width}"/>` : ''}
    <path id="gridlines" d="${lines}" stroke-width="${width}"/>
    <path id="palaces" d="${palace}" stroke-width="${width}"/>
  </g>
</svg>
`;
  writeFileSync(new URL(`../../public/images/board/svg/${theme}-minixiangqi.svg`, import.meta.url), svg);
  dom.window.close();
}

// Reuse the canonical Kai outlines, with seven player-relative files in each orientation.
const coordinates = new JSDOM(
  readFileSync(
    new URL('../../public/images/board/svg/xiangqi-file-coordinates.svg', import.meta.url),
    'utf8',
  ),
  { contentType: 'image/svg+xml' },
);
const glyphs = ['arabic', 'hanzi'].flatMap(script =>
  Array.from({ length: 7 }, (_, index) => {
    const glyph = coordinates.window.document.getElementById(`${script}-${index + 1}`).cloneNode(true);
    glyph.setAttribute('transform', 'scale(.10528)');
    return glyph.outerHTML;
  }),
);
const rows = ['arabic', 'hanzi', 'hanzi', 'arabic'].map(
  (script, row) =>
    `<g transform="translate(0 ${row * 42})">${Array.from({ length: 7 }, (_, index) => {
      const x = (row < 2 ? 3 - index : index - 3) * 100;
      return `<use href="#${script}-${index + 1}" transform="translate(${x})"/>`;
    }).join('')}</g>`,
);
writeFileSync(
  new URL('../../public/images/board/svg/minixiangqi-file-coordinates.svg', import.meta.url),
  `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" fill="#866855" viewBox="-350 -21 700 168">
  <title>Mini Xiangqi file coordinates</title>
  <defs>${glyphs.join('\n')}</defs>
  ${rows.join('\n')}
</svg>
`,
);
coordinates.window.close();
