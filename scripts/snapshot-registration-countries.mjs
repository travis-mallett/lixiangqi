// The profile flag catalogue owns registration choices in all three products.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = readFileSync(resolve(root, 'modules/user/src/main/Flags.scala'), 'utf8');
const countries = [...source.matchAll(/F\("([^"]+)", "([^"]+)"/g)]
  .map(([, code, name]) => [code, name])
  .sort((a, b) => (a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : 0));
if (countries.length < 200) throw new Error('Incomplete profile flag catalogue');
const quote = value => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$')}'`;
const dart = `// Generated by lixiangqi/scripts/snapshot-registration-countries.mjs.\n// Country names match the canonical profile flag catalogue.\nconst registrationCountries = <String, String>{\n${countries.map(([code, name]) => `  ${quote(code)}: ${quote(name)},`).join('\n')}\n};\n`;
const check = process.argv.includes('--check');
for (const app of ['lixiangqi-mobile', 'lixiangqi-mobile-kids']) {
  const path = resolve(root, '..', app, 'lib/features/profile/registration_countries.dart');
  if (check) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== dart)
      throw new Error(`${app}: registration countries are stale`);
  } else writeFileSync(path, dart);
}
