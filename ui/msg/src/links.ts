export function messageLinks(text: string) {
  if (/[\u202c-\u202e]/.test(text)) return [];
  return (parser.match(text) ?? []).filter(match => {
    if (!/^https?:/i.test(match.url) || match.url.length > 4096 || /[\u2500-\u25ff]/.test(match.url))
      return false;
    try {
      const url = new URL(match.url);
      const domain = match.raw
        .replace(/^https?:\/\//i, '')
        .split(/[/?#:]/)[0]
        .replaceAll('.', '');
      return (
        !url.username &&
        !url.password &&
        url.hostname.includes('.') &&
        !url.hostname.split('.').includes('') &&
        !(/[^\x00-\x7f]/.test(domain) && /[a-z0-9]/i.test(domain))
      );
    } catch {
      return false;
    }
  });
}
